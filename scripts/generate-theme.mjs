/**
 * Generates the Material 3 Expressive token stylesheet from one seed colour.
 *
 * The palette comes from Google's Material Color Utilities through
 * `verve-tokens` (HCT dynamic colour + the 2025 expressive role set).
 * Change the seed and re-run `pnpm theme` (also runs before dev/build).
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createTheme, themeToCss } from "verve-tokens";

const seed = "#6750A4"; // Material blue-purple
const theme = createTheme({
  seed,
  variant: "tonalSpot",
  specVersion: "2025",
  platform: "phone",
});

// VitePress puts `.dark` on <html>; verve defaults to [data-theme="dark"].
const rawCss = themeToCss(theme, {
  lightSelector: ":root",
  darkSelector: ".dark",
});

// Verve's type tokens name Roboto Flex. This site self-hosts Google Sans Flex
// + Noto Sans SC, so keep token names and swap only the family stack.
const css = rawCss.replaceAll(
  '"Roboto Flex", Roboto, system-ui, sans-serif',
  '"Google Sans Flex Variable", "Noto Sans SC Variable", "Noto Sans SC", sans-serif',
);

// M3 measurement scale: md.sys.measurement.space100 = 8dp. Nested units
// (2/4/6/10) and the 12/20 steps used by components are included too.
const spacing = {
  25: "2px",
  50: "4px",
  75: "6px",
  100: "8px",
  125: "10px",
  150: "12px",
  200: "16px",
  225: "18px",
  250: "20px",
  300: "24px",
  400: "32px",
  500: "40px",
  600: "48px",
  700: "56px",
  800: "64px",
  900: "72px",
};

const spacingCss = `:root {\n${Object.entries(spacing)
  .map(([step, value]) => `  --md-sys-spacing-${step}: ${value};`)
  .join("\n")}\n}\n`;

const outFile = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../.vitepress/theme/styles/tokens.css",
);

const banner = `/* AUTO-GENERATED by scripts/generate-theme.mjs — do not edit.
 * Seed: ${seed} · color variant: tonalSpot · M3 spec 2025
 * Regenerate: pnpm theme
 */\n\n`;

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, banner + css + "\n" + spacingCss, "utf8");
console.log(`[theme] wrote ${outFile} from seed ${seed}`);
